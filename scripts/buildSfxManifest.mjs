// Turns whatever is sitting in public/sfx into lib/sfxManifest.ts.
//
// Run by `predev` and `prebuild`, so the only thing anyone has to do to add a
// variant is DROP A FILE IN public/sfx. No config to update, no count to keep
// in sync, no code to touch — which is the whole point: the families are
// meant to grow during a soundcheck, not during a sprint.
//
// The FAMILY is the filename with any trailing digits removed, so
// cheers.mp3 + cheers2.mp3 + cheers3.mp3 are three variants of `cheers`, and
// a lone we-love-you-adrian.mp3 is a family of one. That means the convention
// a human has to remember is "name it after the button, add a number" —
// nothing about folders, manifests or ids.
//
// Generated as .ts rather than .json so the Next build, tsc and the Node test
// runner all load it the same way, with no import attributes and no tsconfig
// flags beyond what the repo already sets.
import { readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname, extname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SFX_DIR = join(here, "..", "public", "sfx");
const OUT = join(here, "..", "lib", "sfxManifest.ts");

// Only what a browser will actually decode via decodeAudioData.
const PLAYABLE = new Set([".mp3", ".m4a", ".wav", ".ogg", ".aac", ".flac"]);

const familyOf = (stem) => stem.replace(/\d+$/, "");

// Natural order, so cheers2 sorts before cheers10 rather than after it. The
// order only has to be STABLE — the engine picks at random — but a manifest
// that reshuffles itself on every run makes for a useless diff.
const natural = (a, b) =>
  a.localeCompare(b, "en", { numeric: true, sensitivity: "base" });

const families = new Map();
for (const name of readdirSync(SFX_DIR)) {
  const ext = extname(name).toLowerCase();
  if (!PLAYABLE.has(ext)) continue;
  const family = familyOf(basename(name, extname(name)));
  if (!family) continue;
  if (!families.has(family)) families.set(family, []);
  families.get(family).push(name);
}

const sorted = [...families.entries()].sort((a, b) => natural(a[0], b[0]));
const body = sorted
  .map(
    ([family, files]) =>
      `  "${family}": [\n` +
      files
        .sort(natural)
        .map((f) => `    "/sfx/${f}",`)
        .join("\n") +
      "\n  ],"
  )
  .join("\n");

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  `// GENERATED by scripts/buildSfxManifest.mjs — do not edit by hand.
// Add or remove files in public/sfx and this is rebuilt by predev/prebuild.

export const SFX_FAMILIES: Record<string, readonly string[]> = {
${body}
};

export type SfxFamily = keyof typeof SFX_FAMILIES;
`
);

const total = sorted.reduce((n, [, f]) => n + f.length, 0);
console.log(
  `sfx manifest: ${sorted.length} families, ${total} files\n` +
    sorted
      .map(([f, files]) => `  ${f.padEnd(22)} ${files.length}`)
      .join("\n")
);
